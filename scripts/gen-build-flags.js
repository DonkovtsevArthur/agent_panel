#!/usr/bin/env node
/**
 * Generates corporate build artifacts from HARBOR_CORPORATE:
 *   - src/buildFlags.generated.ts  (extension host / tsc)
 *   - media/src/panel/corporate-config.js  (webview panel, inside IIFE)
 *
 * HARBOR_CORPORATE=1 — corporate (Severstal) build: Gennadiy gateway
 * preset + Keycloak SSO URLs stay in the package.
 * HARBOR_CORPORATE=0 — public Marketplace build: those hostnames must not
 * appear in out/, media/panel.js, or the VSIX.
 *
 * Default when unset: corporate ON (this private repo's daily compile).
 * `npm run package` always forces HARBOR_CORPORATE=0.
 */

const fs = require("fs");
const path = require("path");

const corporate = !(
  process.env.HARBOR_CORPORATE === "0" ||
  process.env.HARBOR_CORPORATE === "false"
);

const root = path.join(__dirname, "..");

const tsPath = path.join(root, "src", "buildFlags.generated.ts");
const tsSource = `// Generated by scripts/gen-build-flags.js — do not edit.
// HARBOR_CORPORATE=${corporate ? "1" : "0"}

export const CORPORATE_BUILD = ${corporate ? "true" : "false"};

/** OpenAI-compatible Gennadiy gateway base URL (empty on public builds). */
export const GENNADIY_GATEWAY_BASE_URL = ${
  corporate
    ? '"https://gennadiy-test.kube.severstal.severstalgroup.com/gennadiy/v1"'
    : '""'
};

/** Keycloak SSO for \`gennadiy auth login\` (empty URL on public builds). */
export const GENNADIY_KEYCLOAK_URL = ${
  corporate ? '"https://sso-id-test-int.severstal.com"' : '""'
};

export const GENNADIY_KEYCLOAK_REALM = "common";
export const GENNADIY_KEYCLOAK_CLIENT_ID = "gennadiy-df";
`;
fs.writeFileSync(tsPath, tsSource, "utf8");

const panelPath = path.join(root, "media", "src", "panel", "corporate-config.js");
const panelSource = `// Generated by scripts/gen-build-flags.js — do not edit.
// HARBOR_CORPORATE=${corporate ? "1" : "0"}

const CORPORATE_BUILD = ${corporate ? "true" : "false"};
const CORPORATE_PROVIDER_PRESETS = ${
  corporate
    ? `[
  {
    id: "gennadiy",
    name: "Gennadiy",
    baseUrl: "https://gennadiy-test.kube.severstal.severstalgroup.com/gennadiy/v1",
  },
]`
    : "[]"
};
`;
fs.writeFileSync(panelPath, panelSource, "utf8");

console.log(
  `Wrote build flags (CORPORATE_BUILD=${corporate ? "true" : "false"}) → ${tsPath}, ${panelPath}`
);
